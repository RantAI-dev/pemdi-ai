/**
 * Writes tests/parity/<module>.cases: generated inputs run through the oracle. Never edit a case
 * file by hand. A fixed seed keeps the file stable; pass another seed for unseen cases at review.
 *
 *   bun scripts/oracle/cases.ts <module> [seed] [out]
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const mod = process.argv[2] ?? "";
const seed = Number(process.argv[3] ?? 1);
const out = process.argv[4] ?? `tests/parity/${mod}.cases`;

let s = seed >>> 0 || 1;
const rnd = () => {
  s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
  return s / 2 ** 32;
};
const pick = <T>(xs: T[]): T => xs[Math.floor(rnd() * xs.length)] as T;
const n = () => Math.round((rnd() * 400 - 100) * 1000) / 1000;

// Edge values from the "what differs" list: zero, negative zero, thresholds, ties, large, tiny.
const EDGE = [0, -0, 1, -1, 0.5, -0.5, 50.9999, 51, 65.99, 66, 75.999, 76, 90.99, 91, 100, 1e15, -1e15, 1e-12];

const GEN: Record<string, () => { fn: string; args: unknown[] }[]> = {
  "makro-hitung": () => {
    const rows: { fn: string; args: unknown[] }[] = [];
    for (const a of EDGE) for (const b of [0, 1, -1, 100, 0.001]) rows.push({ fn: "laju", args: [a, b] });
    for (const a of EDGE) for (const p of ["naik", "turun"]) rows.push({ fn: "lajuBaik", args: [a, p] });
    for (const a of EDGE) for (const t of [0, 100, -50]) for (const p of ["naik", "turun"]) rows.push({ fn: "capaian", args: [a, t, p] });
    for (const a of EDGE) rows.push({ fn: "kategori", args: [a] });
    for (let i = 0; i < 200; i++) {
      const fn = pick(["laju", "lajuBaik", "capaian", "kategori"]);
      const p = pick(["naik", "turun"]);
      rows.push({ fn, args: fn === "laju" ? [n(), n()] : fn === "lajuBaik" ? [n(), p] : fn === "capaian" ? [n(), n(), p] : [n()] });
    }
    return rows;
  },
};

const gen = GEN[mod];
if (!gen) {
  console.error(`cases: no generator for "${mod}". Known: ${Object.keys(GEN).join(", ")}`);
  process.exit(2);
}
const input = gen().map((r) => JSON.stringify(r)).join("\n");
const p = spawnSync("bun", ["scripts/oracle/run.ts", mod], { input, encoding: "utf8" });
if (p.status !== 0) {
  console.error(p.stderr);
  process.exit(p.status ?? 1);
}
const header = `# Generated by: bun scripts/oracle/cases.ts ${mod} ${seed}\n# Do not edit by hand.\n`;
writeFileSync(out, header + p.stdout);
console.log(`cases: wrote ${out}`);
